
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import pandas as pd


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Compare selected samples between active-learning strategies")
    p.add_argument("--history", required=True, help="*.history.json generated by fairal-run --save-history")
    p.add_argument("--strategy-a", default="baal")
    p.add_argument("--strategy-b", default="baal_random_pareto")
    p.add_argument("--out", required=True)
    return p.parse_args()


def load_history(path: str | Path) -> list[dict[str, Any]]:
    with Path(path).open("r", encoding="utf-8") as f:
        return json.load(f)


def main() -> None:
    args = parse_args()
    hist = load_history(args.history)
    rows: list[dict[str, Any]] = []
    by_key: dict[tuple[Any, ...], dict[str, Any]] = {}
    for h in hist:
        key = (h.get("dataset"), h.get("backend"), h.get("seed"), h.get("round"), h.get("strategy"))
        by_key[key] = h

    keys_a = [k for k in by_key if k[-1] == args.strategy_a]
    for ka in sorted(keys_a):
        kb = ka[:-1] + (args.strategy_b,)
        if kb not in by_key:
            continue
        a = set(map(int, by_key[ka].get("selected_indices", [])))
        b = set(map(int, by_key[kb].get("selected_indices", [])))
        union = a | b
        inter = a & b
        rows.append(
            {
                "dataset": ka[0],
                "backend": ka[1],
                "seed": ka[2],
                "round": ka[3],
                "strategy_a": args.strategy_a,
                "strategy_b": args.strategy_b,
                "n_a": len(a),
                "n_b": len(b),
                "n_intersection": len(inter),
                "n_union": len(union),
                "jaccard": len(inter) / len(union) if union else 1.0,
                "identical": a == b,
            }
        )
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(rows)
    df.to_csv(out, index=False)
    if not df.empty:
        print(df.groupby(["strategy_a", "strategy_b"])[["jaccard", "identical"]].agg(["mean", "sum", "count"]))
    print(f"Saved history comparison to {out}")


if __name__ == "__main__":
    main()

